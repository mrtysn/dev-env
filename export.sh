      "Use Non-ASCII Font": false
    }
  ]
}
EOF
    mv iterm-profiles/font-only.json.tmp iterm-profiles/font-only.json
    note "iterm-profiles/font-only.json"
fi

# Export window & keyboard configs (Phoenix window manager, Karabiner keymaps)
# Both are portable, non-secret text — safe for this public repo.
echo "✓ Exporting window & keyboard configs"

if [ -f ~/.phoenix.js ]; then
    copy_atomic ~/.phoenix.js .phoenix.js
    echo "  Exported ~/.phoenix.js"
    note ".phoenix.js"
else
    warn "~/.phoenix.js not found, skipping"
fi

# Karabiner: only karabiner.json — never assets/ or automatic_backups/ (churny local state).
if [ -f ~/.config/karabiner/karabiner.json ]; then
    mkdir -p karabiner
    copy_atomic ~/.config/karabiner/karabiner.json karabiner/karabiner.json
    echo "  Exported ~/.config/karabiner/karabiner.json"
    note "karabiner/karabiner.json"
else
    warn "~/.config/karabiner/karabiner.json not found, skipping"
fi

# Check Claude Code settings, every config folder on this machine.
# The repo holds settings as a base plus per-profile overlays (agents/claude/settings.json,
# agents/claude/overlays/), which a live file cannot be split back into. So export writes
# nothing here: it refuses a folder whose live settings.json differs from base + the overlays
# of the profile it declares, and names the keys. Port the change into the base (valid on
# every machine and profile) or the profile's overlay, then run import.sh step 12.
# *.local.json (machine-local) and memory/ (private) are never read.
echo "✓ Checking Claude Code settings against base + profile overlays"
SETTINGS_TOOL="$SCRIPT_DIR/agents/claude/settings-profile.sh"
for cfg in "${(@f)$("$SETTINGS_TOOL" dirs)}"; do
    shown="${cfg/#$HOME/~}"
    [ -f "$cfg/settings.json" ] || { warn "$shown/settings.json not found, skipping"; continue; }
    profile="$("$SETTINGS_TOOL" profile "$cfg")"
    if [[ -z "$profile" ]]; then
        fail "$shown/paths.local.sh declares no AGENT_PROFILE — set it with: CLAUDE_DIR=$shown agents/claude/write-paths-local.sh --profile <${MACHINE_PROFILES[*]:-personal|work}>"
        continue
    fi
    if check_out="$("$SETTINGS_TOOL" check "$cfg" "$profile" 2>&1)"; then
        echo "  $shown matches base + $profile"
    else
        print -r -- "$check_out" | sed 's/^/  /'
        fail "$shown/settings.json differs from base + '$profile' (keys above) — move the change into agents/claude/settings.json or overlays/$profile*.json, then re-run import.sh step 12"
    fi
done

# Export lazygit + repo-tabs config (git TUI workflow).
# ~/.config/repo-tabs/repos.txt (work repo paths — this repo is PUBLIC) and
# sessions.json (runtime state) are deliberately never read here.
echo "✓ Exporting lazygit + repo-tabs configuration"
LAZYGIT_DIR="$HOME/Library/Application Support/lazygit"
if [ -f "$LAZYGIT_DIR/config.yml" ]; then
    mkdir -p lazygit/themes
    copy_atomic "$LAZYGIT_DIR/config.yml" lazygit/config.yml
    # The editor preset is per machine (import.sh step 14 sets it from the editor installed
    # there); the repo copy keeps it empty, so $EDITOR applies wherever no known editor exists.
    sed -E 's/^([[:space:]]*)editPreset:.*/\1editPreset: ""/' lazygit/config.yml > lazygit/config.yml.tmp && mv lazygit/config.yml.tmp lazygit/config.yml
    note "lazygit/config.yml (editPreset reset: set per machine on import)"
    for t in "$LAZYGIT_DIR"/themes/*.yml(N); do
        copy_atomic "$t" "lazygit/themes/${t:t}"
        note "lazygit/themes/${t:t}"
    done
else
    warn "$LAZYGIT_DIR/config.yml not found, skipping lazygit"
fi
for g in work personal; do
    if [ -f ~/.config/repo-tabs/theme-$g ]; then
        mkdir -p repo-tabs
        copy_atomic ~/.config/repo-tabs/theme-$g repo-tabs/theme-$g
        note "repo-tabs/theme-$g"
    fi
done

# App settings: only the keys each app's allowlist in app-settings/apps.json names.
echo "✓ Exporting app settings"
if "$SCRIPT_DIR/app-settings/app-settings.py" export --label "$MACHINE_LABEL"; then
    note "app-settings/ (allowlisted keys)"
