#!/bin/zsh
# Export current terminal configuration to this repository

set -euo pipefail

# --yes: skip the "Continue?" question (an agent's shell has no terminal to answer it).
ASSUME_YES=false
case "${1:-}" in
    "") ;;
    --yes|-y) ASSUME_YES=true ;;
    *) echo "usage: ./export.sh [--yes]" >&2; exit 2 ;;
esac

SCRIPT_DIR="$(cd "$(dirname "${0}")" && pwd)"
cd "$SCRIPT_DIR"

HOSTNAME=$(hostname -s)
USERNAME=$(whoami)
DATE=$(date +"%Y-%m-%d %H:%M")

# Machine → label and profiles mapping: single source of truth.
source "$SCRIPT_DIR/machine-label.sh"

# ── Bookkeeping ────────────────────────────────────────────────────────────────
# The closing summary is driven by what was actually written, not by a
# hand-maintained list that drifts from reality.
EXPORTED=()
WARNINGS=()
FAILURES=()

note()    { EXPORTED+=("$1") }
warn()    { WARNINGS+=("$1"); echo "  ! $1" }
fail()    { FAILURES+=("$1"); echo "  ✗ $1" }

# Copy via a temp file so an interrupted run can't leave a tracked file truncated.
copy_atomic() {
    cp "$1" "$2.tmp" && mv "$2.tmp" "$2"
}

echo "=== Exporting dev environment configuration ==="
echo ""
echo "Computer: $HOSTNAME"
echo "User: $USERNAME"
echo ""
echo "This will export your ~/.zshrc, ~/.p10k.zsh, tmux config, iTerm2 profiles and app-level"
echo "settings and Phoenix + Karabiner configs to this repository, and checks every Claude Code"
echo "config folder against the repo's base + profile settings."
echo ""
echo "Files in this repo that may be overwritten:"
echo "  - $SCRIPT_DIR/.zshrc.base, .zshrc.loader, and this machine's .zshrc.${MACHINE_LABEL:-<label>}"
echo "  - $SCRIPT_DIR/.p10k.zsh"
echo "  - $SCRIPT_DIR/plugins.list"
echo "  - $SCRIPT_DIR/iterm-profiles/*.json"
echo "  - $SCRIPT_DIR/iterm-settings.json"
echo "  - $SCRIPT_DIR/.phoenix.js"
echo "  - $SCRIPT_DIR/karabiner/karabiner.json"
echo "  - $SCRIPT_DIR/tmux/${MACHINE_LABEL:-<label>}.conf (based on hostname)"
echo "  - $SCRIPT_DIR/lazygit/config.yml, lazygit/themes/*.yml, repo-tabs/theme-*"
echo "  - $SCRIPT_DIR/asdf/tool-versions.${MACHINE_LABEL:-<label>} (this machine's only)"
echo ""
echo "Your actual config files will NOT be modified."
echo ""
if $ASSUME_YES; then
    REPLY=y
elif [[ ! -t 0 ]]; then
    echo "✗ Not a terminal, so there is nobody to ask: re-run with --yes to export without the question" >&2
    exit 2
else
    read "REPLY?Continue? (y/N) "
    REPLY=${REPLY:-N}
fi
if [[ ! $REPLY =~ ^[Yy]$ ]]; then
    echo "Export cancelled."
    exit 0
fi
echo ""

# ── Validate sources BEFORE destroying anything ────────────────────────────────
# The cleanup below removes the repo's only copy of .zshrc.full. Validating first
# means a missing source aborts with the repo intact.
echo "✓ Validating sources"
MISSING=()
[ -f ~/.zshrc ]    || MISSING+=("~/.zshrc")
[ -f ~/.p10k.zsh ] || MISSING+=("~/.p10k.zsh")

if (( ${#MISSING[@]} > 0 )); then
    echo ""
    echo "✗ Required source files not found:"
    for m in "${MISSING[@]}"; do echo "    $m"; done
    echo ""
    echo "Aborting — nothing in the repo was modified."
    exit 1
fi
echo ""

# Zsh split label comes from the shared mapping (machine-label.sh).
ZSH_LABEL="$MACHINE_LABEL"

# Export zsh config — split layout: shared base + per-machine file + loader.
# Only THIS machine's .zshrc.<label> is written; the other machine's file is left
# untouched. That one-sided write is what makes repo→machine imports non-destructive.
echo "✓ Exporting zsh configuration"
if [ -f ~/.zshrc.base ]; then
    copy_atomic ~/.zshrc.base .zshrc.base
    note ".zshrc.base"
    # The loader's hostname cases are edited in the repo when a machine is added, and the
    # live ~/.zshrc only gets them on the next import. Exporting first would drop them.
    lost_loader="$(comm -23 <(grep -E '^ +[A-Za-z0-9-]+\)' .zshrc.loader 2>/dev/null | LC_ALL=C sort) \
                            <(grep -E '^ +[A-Za-z0-9-]+\)' ~/.zshrc | LC_ALL=C sort) || true)"
    if [[ -n "$lost_loader" ]]; then
        # Refuse, not warn: the copy would delete the machine cases from the repo's only
        # loader, and the warning scrolls past before anyone reads it.
        fail ".zshrc.loader NOT overwritten: the repo copy maps machines the live ~/.zshrc lacks. Missing cases:"
        print -r -- "$lost_loader" | sed 's/^/      /'
        echo "      Fix: run ./import.sh (step 8 installs the repo loader as ~/.zshrc), then export again."
    else
        copy_atomic ~/.zshrc .zshrc.loader
        note ".zshrc.loader"
    fi
    if [[ -n "$ZSH_LABEL" ]] && [ -f ~/.zshrc.$ZSH_LABEL ]; then
        copy_atomic ~/.zshrc.$ZSH_LABEL .zshrc.$ZSH_LABEL
        note ".zshrc.$ZSH_LABEL"

        # Generated, read-only full view (base + THIS machine's block) for reading/
        # diffing. import.sh never reads it, so it cannot clobber real config. Each
        # machine refreshes only its own .combined.<label>, so both stay visible.
        {
            echo "# ─── GENERATED by export.sh — DO NOT EDIT ───────────────────────────────────────"
            echo "# Full assembled ~/.zshrc for '$ZSH_LABEL' = .zshrc.base + .zshrc.$ZSH_LABEL."
            echo "# For reading/diffing only. Source of truth is those two files; import.sh"
            echo "# ignores this. Refreshed whenever export.sh runs on this machine."
            echo "# ────────────────────────────────────────────────────────────────────────────────"
            echo ""
            cat ~/.zshrc.base
            echo ""
            cat ~/.zshrc.$ZSH_LABEL
        } > .zshrc.combined.$ZSH_LABEL.tmp && mv .zshrc.combined.$ZSH_LABEL.tmp .zshrc.combined.$ZSH_LABEL
        note ".zshrc.combined.$ZSH_LABEL (generated, read-only)"
    else
        warn "No ~/.zshrc.$ZSH_LABEL for this machine (label='${ZSH_LABEL:-unknown}') — per-machine file not exported"
    fi
    # Drop the deprecated monolith so it can't shadow the split layout on import.
    [ -f .zshrc.full ] && { rm -f .zshrc.full; echo "  Removed deprecated .zshrc.full"; }
else
    # Legacy fallback: this machine hasn't migrated to the split layout yet.
    warn "~/.zshrc.base not found — exporting monolithic ~/.zshrc to .zshrc.full (legacy)"
    copy_atomic ~/.zshrc .zshrc.full
    note ".zshrc.full (legacy)"
fi

# Export .p10k.zsh
echo "✓ Exporting ~/.p10k.zsh"
copy_atomic ~/.p10k.zsh .p10k.zsh
note ".p10k.zsh"

# Export custom plugin list
echo "✓ Scanning custom plugins"
if [ -d ~/.oh-my-zsh/custom/plugins ]; then
    # (N/) = nullglob + directories only; (:t) takes the basename — no forks, no temp file.
    plugin_dirs=(~/.oh-my-zsh/custom/plugins/*(N/))
    plugin_names=(${plugin_dirs:t})
    plugin_names=(${plugin_names:#example})

    print -l -- ${plugin_names:-} > plugins.list.tmp
    mv plugins.list.tmp plugins.list
    echo "  Found ${#plugin_names[@]} custom plugins"
else
    echo "  No custom plugins directory found"
    : > plugins.list
fi
note "plugins.list"

# Brew dependencies live in Brewfile (shared) + Brewfile.<primary profile> + Brewfile.<label> —
# hand-curated tracked files, edited directly, never written by this script and
# never generated via `brew bundle dump`. Export only reports drift against them:
# report-only by design, so silent drift stays loud without auto-adding noise
# (see: lazygit, 2026-07).
if command -v brew >/dev/null 2>&1; then
    echo "✓ Checking brew drift (leaves/casks vs Brewfiles)"
    BREWFILES=(Brewfile)
    [[ -n "$MACHINE_PRIMARY_PROFILE" && -f "Brewfile.$MACHINE_PRIMARY_PROFILE" ]] && BREWFILES+=("Brewfile.$MACHINE_PRIMARY_PROFILE")
    [[ -n "$ZSH_LABEL" && -f "Brewfile.$ZSH_LABEL" ]] && BREWFILES+=("Brewfile.$ZSH_LABEL")
    # Compare top-level installs only — `brew bundle cleanup` would also list
    # every transitive dep, which drowns the signal. || true: comm/grep exit
    # codes would otherwise kill the export under set -e/pipefail.
    WANTED=$(grep -hE '^(brew|cask|mas) ' "${BREWFILES[@]}" | awk -F'"' '{print $2}' | sort -u || true)
    BREW_DRIFT=$(comm -23 <(brew leaves 2>/dev/null | sort) <(echo "$WANTED") | tr '\n' ' ' || true)
    if [[ -n "${BREW_DRIFT// }" ]]; then
        warn "formulae not in ${BREWFILES[*]} (intentional?): $BREW_DRIFT"
    fi
    CASK_DRIFT=$(comm -23 <(brew list --cask 2>/dev/null | sort) <(echo "$WANTED") | tr '\n' ' ' || true)
    if [[ -n "${CASK_DRIFT// }" ]]; then
        warn "casks not in ${BREWFILES[*]} (intentional?): $CASK_DRIFT"
    fi
fi

# Export asdf runtime pins — per-machine file, one-sided write (same convention
# as .zshrc.<label>): each machine backs up only its own pins.
echo "✓ Exporting asdf tool-versions ($ZSH_LABEL)"
if [[ -n "$ZSH_LABEL" ]] && [ -f ~/.tool-versions ]; then
    mkdir -p asdf
    copy_atomic ~/.tool-versions "asdf/tool-versions.$ZSH_LABEL"
    note "asdf/tool-versions.$ZSH_LABEL"
else
    warn "no ~/.tool-versions or unknown machine label — asdf pins not exported"
fi

# Export tmux config
echo "✓ Exporting tmux configuration"
TMUX_TARGET=""

if [[ -n "$MACHINE_LABEL" ]]; then
    TMUX_TARGET="tmux/$MACHINE_LABEL.conf"
    echo "  Detected: $MACHINE_NAME"
else
    warn "Unknown machine (see machine-label.sh), skipping tmux config export"
fi

if [[ -n "$TMUX_TARGET" ]]; then
    mkdir -p tmux

    if [ -f ~/.tmux.conf ]; then
        # Resolve symlink to get actual content
        cp -L ~/.tmux.conf "$TMUX_TARGET.tmp" && mv "$TMUX_TARGET.tmp" "$TMUX_TARGET"
        echo "  Exported ~/.tmux.conf → $TMUX_TARGET"
        note "$TMUX_TARGET"
    else
        warn "~/.tmux.conf not found, skipping"
    fi
fi

# ── iTerm2: profiles AND app-level settings ────────────────────────────────────
# Profiles alone are not enough to reproduce the setup: theme, tab bar geometry,
# the Minimal-theme tuning knobs, global keymaps and pointer actions all live as
# TOP-LEVEL plist keys outside any profile.
#
# Keys are copied verbatim from the live plist and never hand-typed: iTerm reads
# CamelCase names (MinimalDeslectedColoredTabAlpha) while its internal symbols are
# lowercase-first, so a hand-written key list silently produces keys nothing reads.
#
# This repo is PUBLIC. The export applies a denylist for machine-local state and a
# secrets gate that withholds (and reports) anything credential-shaped.
echo "✓ Exporting iTerm2 profiles and settings"
mkdir -p iterm-profiles

ITERM_PLIST="$HOME/Library/Preferences/com.googlecode.iterm2.plist"

if [ ! -f "$ITERM_PLIST" ]; then
    warn "iTerm2 not installed, skipping profiles and settings"
elif ! defaults read com.googlecode.iterm2 &>/dev/null; then
    warn "iTerm2 preferences not readable, skipping profiles and settings"
elif DEV_ENV_DIR="$SCRIPT_DIR" python3 << 'PYTHON_EOF'
import base64
import json
import os
import plistlib
import re
import sys

plist_path = os.path.expanduser("~/Library/Preferences/com.googlecode.iterm2.plist")
profiles_dir = "iterm-profiles"
settings_path = "iterm-settings.json"

# The denylist and the secrets gate (DENY, SECRET) live in iterm-filter.py, shared with import.sh --check.
exec(open(os.path.join(os.environ["DEV_ENV_DIR"], "iterm-filter.py")).read())


def convert_for_json(obj):
    if isinstance(obj, bytes):
        return {"_type": "data", "value": base64.b64encode(obj).decode("ascii")}
    elif isinstance(obj, dict):
        return {k: convert_for_json(v) for k, v in obj.items()}
    elif isinstance(obj, list):
        return [convert_for_json(item) for item in obj]
    else:
        return obj


def name_to_filename(name):
    return name.lower().replace(" ", "-") + ".json"


def write_json_atomic(path, payload):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(payload, f, indent=2, sort_keys=True)
    os.replace(tmp, path)


try:
    with open(plist_path, "rb") as f:
        data = plistlib.load(f)
except Exception as e:
    print(f"  Could not read iTerm2 plist: {e}", file=sys.stderr)
    sys.exit(1)

failed = False

# ── profiles ───────────────────────────────────────────────────────────────────
profiles = data.get("New Bookmarks", [])
if not profiles:
    print("  No profiles found in iTerm2")
else:
    exported = 0
    seen = {}
    written = {}
    for profile in profiles:
        name = profile.get("Name", "Unknown")
        if name in AUTO_CREATED_PROFILES:
            continue
        # A dynamic profile is one import.sh installed from this repo: iTerm2 lists it among the saved ones,
        # filled out with every default and its file's absolute path. Exporting it would copy the repo onto
        # itself, bloated and with this machine's home folder in a public file.
        if profile.get("Is Dynamic Profile") or "Dynamic Profile Filename" in profile:
            print(f"  - {name}: dynamic profile installed from this repo, not exported")
            continue
        filename = name_to_filename(name)

        # Distinct profile names can collapse to one filename (lowercase + hyphenate).
        # Silently overwriting would lose a profile, so refuse and report.
        if filename in seen:
            print(f"  ! Filename collision: '{name}' and '{seen[filename]}' both map to "
                  f"{filename} — skipping '{name}'", file=sys.stderr)
            failed = True
            continue
        seen[filename] = name

        # A file of this name that holds a different profile (another Guid) is not replaced: this machine's
        # profile of that name is a different one (e.g. iTerm2's stock Default next to the repo's customised
        # Default), and the file would be lost.
        target = os.path.join(profiles_dir, filename)
        if os.path.exists(target):
            try:
                old_guids = {p.get("Guid") for p in json.load(open(target)).get("Profiles", [])}
            except Exception as e:
                print(f"  ! {filename} exists but cannot be read ({e}), not overwriting it", file=sys.stderr)
                failed = True
                continue
            if profile.get("Guid") not in old_guids:
                print(f"  ! {filename} holds a different profile (another Guid) than this machine's '{name}': "
                      f"not overwriting it. Rename one of the two profiles, or move the file aside. If it is "
                      f"iTerm2's stock profile, import.sh --check names it and import.sh step 9 offers to remove it",
                      file=sys.stderr)
                failed = True
                continue
        written[profile.get("Guid")] = filename

        try:
            write_json_atomic(target, {"Profiles": [convert_for_json(profile)]})
            print(f"  - {name} -> {filename}")
            exported += 1
        except Exception as e:
            print(f"  Failed to write {filename}: {e}", file=sys.stderr)
            failed = True
    print(f"  Exported {exported} profiles")
    # A profile renamed in iTerm2 is written to a new file; the old file keeps the same Guid, and import would
    # install both. Nothing is deleted here: report it so it is removed by hand once it is known to be the old name.
    for fname in sorted(os.listdir(profiles_dir)):
        if not fname.endswith(".json") or fname == "font-only.json":
            continue
        try:
            guids = {p.get("Guid") for p in json.load(open(os.path.join(profiles_dir, fname))).get("Profiles", [])}
        except Exception:
            continue
        for guid in guids:
            if guid in written and written[guid] != fname:
                print(f"  ! {fname} has the same Guid as the saved profile now exported to {written[guid]}: "
                      f"it is probably the old name; delete {fname} if so", file=sys.stderr)

# ── app-level settings ─────────────────────────────────────────────────────────
settings, withheld, dropped = {}, [], 0
for key, value in data.items():
    if DENY.search(key):
        dropped += 1
        continue
    if looks_secret(key, value):
        withheld.append(key)
        continue
    settings[key] = convert_for_json(value)

try:
    write_json_atomic(settings_path, {
        "_comment": (
            "iTerm2 app-level preferences (top-level plist keys, excluding profiles). "
            "Keys are copied verbatim — iTerm reads CamelCase names, so casing matters. "
            "Applied by import.sh while iTerm2 is NOT running."
        ),
        "settings": settings,
    })
    print(f"  Exported {len(settings)} app-level settings ({dropped} machine-local keys dropped)")
except Exception as e:
    print(f"  Failed to write {settings_path}: {e}", file=sys.stderr)
    failed = True

if withheld:
    print(f"  ! WITHHELD {len(withheld)} credential-shaped keys (repo is public): "
          + ", ".join(withheld), file=sys.stderr)

sys.exit(1 if failed else 0)
PYTHON_EOF
then
    note "iterm-profiles/*.json"
    note "iterm-settings.json"
else
    fail "iTerm2 export failed — profiles and settings may be stale or incomplete"
fi

# clo (agents-shared) expects iTerm to open tmux windows as tabs and bury the tmux client.
# Those prefs are only in the live plist, so a machine that never set them exports nothing
# and every other machine inherits the gap. Say so here, not as a warning from clo later.
for tmux_key in OpenTmuxWindowsIn AutoHideTmuxClientSession TmuxUsesDedicatedProfile; do
    if command -v defaults >/dev/null 2>&1 && ! defaults read com.googlecode.iterm2 "$tmux_key" &>/dev/null; then
        warn "iTerm2 tmux pref $tmux_key is unset on this machine, so iterm-settings.json cannot carry it (set it in iTerm Settings > General > tmux, then re-run export.sh)"
    fi
done

# Create font-only profile if it doesn't exist
if [ ! -f iterm-profiles/font-only.json ]; then
    echo "✓ Creating font-only profile template"
    cat > iterm-profiles/font-only.json.tmp << 'EOF'
{
  "Profiles": [
    {
      "Name": "Dev Config (Font Only)",
      "Guid": "DEV-CONFIG-FONT-ONLY-0001",
